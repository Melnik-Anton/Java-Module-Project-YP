public class Automobile { // создаём класс автомобиль
    String name; // переменная для названия автомобиля
    int speed; // переменная для скорости автомобиля
    Automobile(String name, int speed) { // конструктор параметров каждого автомобиля
        this.name = name; // присвоение параметра имя
        this.speed = speed; // присвоение параметра скорость

    }
}